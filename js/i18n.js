const Lang = (() => {
  let cur = 'ja';
  // lấy câu theo khóa, điền {biến}
  function t(key, vars) {
    let s = (I18N[cur] && I18N[cur][key]) ?? I18N.vi[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
    return s;
  }
  // tên món / nguyên liệu dạng { vi: '…', ja: '…' }
  const name = obj => (typeof obj === 'string' ? obj : obj[cur] || obj.vi);
  // phông chữ cho canvas theo ngôn ngữ
  const font = () => (cur === 'ja' ? "'M PLUS Rounded 1c', 'Be Vietnam Pro', sans-serif" : "'Be Vietnam Pro', 'M PLUS Rounded 1c', sans-serif");
  // đổi ngôn ngữ và cập nhật mọi chữ cố định trong HTML (data-i18n…)
  function set(l) {
    cur = I18N[l] ? l : 'ja';
    document.documentElement.lang = cur;
    document.title = t('docTitle');
    document.querySelectorAll('[data-i18n]').forEach(e => { e.textContent = t(e.dataset.i18n); });
    document.querySelectorAll('[data-i18n-html]').forEach(e => { e.innerHTML = t(e.dataset.i18nHtml); });
    document.querySelectorAll('[data-i18n-ph]').forEach(e => { e.placeholder = t(e.dataset.i18nPh); });
    document.querySelectorAll('[data-i18n-aria]').forEach(e => { e.setAttribute('aria-label', t(e.dataset.i18nAria)); });
  }
  return { t, name, font, set, get: () => cur };
})();
